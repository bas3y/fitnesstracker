// Emojis gibt es mit und ohne Varianten-Selektor (U+FE0F)
const withoutVariant = (text: string) => text.replace(/️/g, '');
const EMOJI_LOOKUP = new Map(
  Object.entries(EMOJI_ICONS).map(([emoji, icon]) => [withoutVariant(emoji), icon]),
);

/** Gespeichertes Symbol (auch altes Emoji) → Symbol-Name; Unbekanntes → `fallback` */
export function toIconName<T extends IconName | ''>(value: string, fallback: T): IconName | T {
  const trimmed = value.trim();
  if (isIconName(trimmed)) return trimmed;
  return EMOJI_LOOKUP.get(withoutVariant(trimmed)) ?? fallback;
}
